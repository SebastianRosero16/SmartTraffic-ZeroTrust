CREATE TABLE traffic_reading_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id VARCHAR(255) NOT NULL,
    operation VARCHAR(16) NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    sensor_id VARCHAR(255) NOT NULL,
    zone_id VARCHAR(255) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    vehicle_count INTEGER NOT NULL,
    CONSTRAINT ck_traffic_reading_audit_operation CHECK (operation = 'INSERT'),
    CONSTRAINT ck_traffic_reading_audit_vehicle_count_non_negative CHECK (vehicle_count >= 0)
);

CREATE INDEX ix_traffic_reading_audit_event_id ON traffic_reading_audit (event_id);

CREATE FUNCTION audit_traffic_reading_insert() RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO traffic_reading_audit (
        event_id, operation, sensor_id, zone_id, occurred_at, vehicle_count)
    VALUES (
        NEW.event_id, 'INSERT', NEW.sensor_id, NEW.zone_id, NEW.occurred_at, NEW.vehicle_count);
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_traffic_readings_audit_insert
AFTER INSERT ON traffic_readings
FOR EACH ROW EXECUTE FUNCTION audit_traffic_reading_insert();

CREATE FUNCTION reject_traffic_history_mutation() RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Table % is append-only', TG_TABLE_NAME
        USING ERRCODE = '55000';
END;
$$;

CREATE TRIGGER trg_traffic_readings_reject_mutation
BEFORE UPDATE OR DELETE ON traffic_readings
FOR EACH ROW EXECUTE FUNCTION reject_traffic_history_mutation();

CREATE TRIGGER trg_traffic_readings_reject_truncate
BEFORE TRUNCATE ON traffic_readings
FOR EACH STATEMENT EXECUTE FUNCTION reject_traffic_history_mutation();

CREATE TRIGGER trg_traffic_reading_audit_reject_mutation
BEFORE UPDATE OR DELETE ON traffic_reading_audit
FOR EACH ROW EXECUTE FUNCTION reject_traffic_history_mutation();

CREATE TRIGGER trg_traffic_reading_audit_reject_truncate
BEFORE TRUNCATE ON traffic_reading_audit
FOR EACH STATEMENT EXECUTE FUNCTION reject_traffic_history_mutation();
